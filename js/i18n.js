function detect() {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved && STR[saved]) return saved;
  } catch { /* private mode */ }
  const nav = (navigator.languages || [navigator.language || "ar"]).map((l) => l.slice(0, 2));
  return nav.find((l) => STR[l]) || "ar";
}

let lang = detect();

export const getLang = () => lang;
export const isRtl = () => lang === "ar";

/** The text for a key in the current language, with {name} placeholders filled in. */
export function t(key, vars = {}) {
  const s = STR[lang][key] ?? STR.ar[key] ?? key;
  return typeof s === "string" ? s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`)) : s;
}

/** Switch language: remember it and update every element marked data-i18n / data-i18n-aria. */
export function setLang(next) {
  if (!STR[next]) return;
  lang = next;
  try { localStorage.setItem(KEY, next); } catch { /* private mode */ }
  applyStatic();
}

export function applyStatic() {
  document.documentElement.lang = lang;
  document.documentElement.dir = isRtl() ? "rtl" : "ltr";
  document.title = t("title");
  document.querySelectorAll("[data-i18n]").forEach((e) => { e.textContent = t(e.dataset.i18n); });
  document.querySelectorAll("[data-i18n-aria]").forEach((e) => e.setAttribute("aria-label", t(e.dataset.i18nAria)));
}
